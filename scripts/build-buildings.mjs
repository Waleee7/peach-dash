// Keys the green-screen building sheets in art-src into transparent atlases, cuts street parts out of the mockups, and writes the atlas table.
// Usage: node scripts/build-buildings.mjs [mockupDir]
import { chromium } from '/Users/walee2/.claude/scripts/node_modules/playwright/index.mjs'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
const dl = process.argv[2] || join(process.env.HOME, 'Downloads')
const uri = p => 'data:image/jpeg;base64,' + readFileSync(p).toString('base64')
const b = await chromium.launch(), page = await b.newPage()
const save = (name, data) => { const buf = Buffer.from(data.split(',')[1], 'base64'); writeFileSync(`public/art/${name}.webp`, buf); console.log(name, Math.round(buf.length / 1024) + 'KB') }
const atlas = {}
for (const sheet of ['towers', 'midrise', 'mids2', 'mids3', 'mids4', 'lofts', 'trees']) {
  const r = await page.evaluate(async ({ u, sheet }) => {
    const i = new Image(); i.src = u; await i.decode()
    const w = i.width, h = i.height, c = document.createElement('canvas'); c.width = w; c.height = h
    const x = c.getContext('2d', { willReadFrequently: true }); x.drawImage(i, 0, 0)
    const im = x.getImageData(0, 0, w, h), d = im.data, on = new Uint8Array(w * h), rows = new Uint32Array(h)
    for (let n = 0, p = 0; n < w * h; n++, p += 4) {
      const R = d[p], G = d[p + 1], B = d[p + 2], key = G - Math.max(R, B), a = key > 90 ? 0 : key < 35 ? 255 : Math.round(255 * (90 - key) / 55)
      d[p + 3] = a; if (key > 0) d[p + 1] = Math.max(R, B)      // pull the green spill off the edges
      if (a > 128) { on[n] = 1; rows[Math.floor(n / w)]++ }
    }
    x.putImageData(im, 0, 0)
    // find each row of assets, then the runs of solid columns within it; thin strays such as wires don't split or merge anything
    const items = [], bands = []; let s0 = -1
    for (let cy = 0; cy <= h; cy++) { const hit = cy < h && rows[cy] > 3; if (hit && s0 < 0) s0 = cy; if (!hit && s0 >= 0) { if (cy - s0 > 40) bands.push([s0, cy]); s0 = -1 } }
    for (const [y0, y1] of bands) {
      const solid = new Uint32Array(w); for (let cy = y0; cy < y1; cy++) for (let cx = 0; cx < w; cx++) solid[cx] += on[cy * w + cx]
      let s = -1
      for (let cx = 0; cx <= w; cx++) { const hit = cx < w && solid[cx] > 3; if (hit && s < 0) s = cx; if (!hit && s >= 0) { if (cx - s > 40) { let t = y1, e = y0; for (let k = s; k < cx; k++) for (let cy = y0; cy < y1; cy++) if (on[cy * w + k]) { if (cy < t) t = cy; if (cy > e) e = cy } items.push({ x: s, y: t, w: cx - s, h: e - t + 1 }) } s = -1 } }
    }
    if (sheet === 'lofts') {
      // lit windows become one glowing shape: a dark pane divider with glow on both sides takes on that glow. Only in the window band, so the murals below stay crisp.
      const glow = (a, p) => a[p] + a[p + 1] + a[p + 2] > 330 && Math.max(a[p], a[p + 1], a[p + 2]) - Math.min(a[p], a[p + 1], a[p + 2]) > 60
      for (const it of items) for (let pass = 0; pass < 3; pass++) {
        const src = d.slice(), R = 7, y0 = Math.floor(it.y + it.h * 0.12), y1 = Math.floor(it.y + it.h * 0.5)
        const near = (p, step) => { for (let k = 1; k <= R; k++) { const q = p + step * k * 4; if (q >= 0 && q < src.length && glow(src, q)) return q } return -1 }
        for (let cy = y0; cy < y1; cy++) for (let cx = it.x; cx < it.x + it.w; cx++) { const p = (cy * w + cx) * 4; if (d[p + 3] < 200 || glow(src, p)) continue; let a = near(p, -1), b = near(p, 1); if (a < 0 || b < 0) { a = near(p, -w); b = near(p, w) } if (a >= 0 && b >= 0) for (let c = 0; c < 3; c++) d[p + c] = (src[a + c] + src[b + c]) / 2 }
      }
      x.putImageData(im, 0, 0)
    }
    return { w, h, items, data: c.toDataURL('image/webp', 0.92) }
  }, { u: uri(`art-src/${sheet}.jpg`), sheet })
  save('bld-' + sheet, r.data); atlas[sheet] = { w: r.w, h: r.h, items: r.items }; console.log(sheet, r.items.length, 'buildings', r.items.map(i => `${i.w}x${i.h}`).join(' '))
}
writeFileSync('src/game/buildingAtlas.ts', '// Generated by scripts/build-buildings.mjs\nexport const BUILDING_ATLAS: Record<string, { w: number; h: number; items: { x: number; y: number; w: number; h: number }[] }> = ' + JSON.stringify(atlas) + '\n')
